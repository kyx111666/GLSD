def digest(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def json_write(path, value):
    Path(path).write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False), encoding="utf-8")


def csv_write(path, rows):
    with Path(path).open("w", newline="", encoding="utf-8-sig") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


@dataclass(frozen=True)
class Config:
    kind: str
    smooth: float
    p: float
    distance: float
    scales: str = "single"
    association: float = 0.0
    aggregation: str = "none"
    tau: float = 0.0
    weight: float = 1.0

    @property
    def identifier(self):
        return "|".join(f"{key}={value:g}" if isinstance(value, float) else f"{key}={value}"
                        for key, value in asdict(self).items())

    @property
    def generation(self):
        return self.scales, self.smooth, self.p, self.distance, self.association


def configuration_grid():
    components = sorted({(round(cs * scale, 8), round(distance * scale, 8))
                         for cs in SMOOTH for distance in DISTANCE
                         for scales in SCALE_SETS.values() for scale in scales})
    configs = [Config("single", cs, p, distance) for cs, distance in components for p in P_VALUES]
    single_count = len(configs)
    batches = []
    for scales in SCALE_SETS:
        for cs in SMOOTH:
            for p in P_VALUES:
                for distance in DISTANCE:
                    for association in ASSOCIATION:
                        start = len(configs)
                        configs.append(Config("union", cs, p, distance, scales, association))
                        for aggregation in AGGREGATION:
                            for tau in TAUS:
                                for weight in WEIGHTS:
                                    configs.append(Config("score", cs, p, distance, scales,
                                                          association, aggregation, tau, weight))
                        batches.append(np.arange(start, len(configs)))
    return configs, single_count, batches


def load_data(backbone, dataset):
    if backbone == "metst":
        path = ME_CACHE / f"{dataset}_strategy1_outputs.pkl"
    else:
        stem = "casme_3" if dataset == "casme3" else dataset
        path = WORKSPACE / backbone / "curve_cache" / f"{stem}_curves.pkl"
    with path.open("rb") as handle:
        package = pickle.load(handle)
    records = []
    for i, source in enumerate(package["records"]):
        curve = np.asarray(source["score"] if backbone == "metst" else package["curves"][i], dtype=float)
        gt = source["samples"] if backbone == "metst" else source["gt"]
        if curve.ndim != 1 or len(curve) < 3 or not np.isfinite(curve).all():
            raise ValueError(f"Invalid curve {i}")
        records.append({"subject": str(source["subject"]), "video": str(source["video"]),
                        "gt": [[int(v) for v in event] for event in gt], "curve": curve})
    subjects = sorted({record["subject"] for record in records}, key=lambda value: (int(value), value))
    if len(records) != (79 if dataset == "sammlv" else 462):
        raise ValueError("Unexpected video count")
    if len(subjects) != (29 if dataset == "sammlv" else 94):
        raise ValueError("Unexpected subject count")
    legacy_k = int(package["k_p"]) if backbone == "metst" else duration_k(records, set(), backbone)
    return records, subjects, legacy_k, path


def duration_k(records, excluded, backbone):
    durations = sorted(event[2] - event[0] for record in records
                       if record["subject"] not in excluded for event in record["gt"])
    if not durations:
        raise ValueError("No training durations")
    value = float(np.mean(durations)) if backbone == "metst" else durations[len(durations) // 2]
    return max(1, int((value + 1) / 2))


def fold_priors(records, subjects, backbone):
    outer = np.array([duration_k(records, {subject}, backbone) for subject in subjects], dtype=int)
    inner = np.zeros((len(subjects), len(subjects)), dtype=int)
    for i, first in enumerate(subjects):
        for j in range(i + 1, len(subjects)):
            inner[i, j] = inner[j, i] = duration_k(records, {first, subjects[j]}, backbone)
    return outer, inner


def robust_z(values):
    values = np.asarray(values, dtype=float)
    if not len(values):
        return values
    median = float(np.median(values))
    scale = 1.4826 * float(np.median(np.abs(values - median)))
    if scale <= 1e-12:
        scale = float(np.std(values))
    return (values - median) / scale if scale > 1e-12 else np.zeros_like(values)


def associate(candidates, tolerance):
    """Height-seeded, non-chaining clusters, with at most one peak per scale."""
    points = sorted((float(height), int(peak), scale)
                    for scale, entries in enumerate(candidates) for peak, height in entries)
    points.sort(key=lambda item: (-item[0], item[1], item[2]))
    used = set()
    output = []
    for index, (height, peak, scale) in enumerate(points):
        if index in used:
            continue
        used.add(index)
        heights = [height]
        for other_scale in range(len(candidates)):
            if other_scale == scale:
                continue
            eligible = [(abs(item[1] - peak), -item[0], item[1], other)
                        for other, item in enumerate(points)
                        if other not in used and item[2] == other_scale and abs(item[1] - peak) <= tolerance]
            if eligible:
                chosen = min(eligible)[-1]
                used.add(chosen)
                heights.append(points[chosen][0])
        heights.sort(reverse=True)
        output.append((peak, len(heights), max(heights), float(np.mean(heights)), float(np.mean(heights[:2]))))
    return sorted(output)


class VideoFeatures:
    def __init__(self, record, k, backbone):
        self.record = record
        self.curve = record["curve"]
        self.k = k
        self.backbone = backbone
        self.smooth = {}
        self.extrema = {}
        self.intervals = {}

    def physical_scale(self, smooth, distance):
        return max(1, round(smooth * self.k)), max(1, round(distance * self.k))

    def candidates(self, smooth, distance, p):
        width, gap = self.physical_scale(smooth, distance)
        if width not in self.smooth:
            smoothed = np.convolve(self.curve, np.ones(width, dtype=float) / width, mode="same")
            mean = float(smoothed.mean())
            self.smooth[width] = smoothed, mean, float(smoothed.max() - mean)
        smoothed, mean, spread = self.smooth[width]
        if (width, gap) not in self.extrema:
            self.extrema[width, gap] = find_peaks(smoothed, distance=gap)[0]
        peaks = self.extrema[width, gap]
        peaks = peaks[smoothed[peaks] >= mean + p * spread]
        return [(int(peak), float((smoothed[peak] - mean) / max(spread, 1e-12))) for peak in peaks]

    def interval(self, peak):
        if peak not in self.intervals:
            if self.backbone == "boostingvrme":
                value = source_interval(self.curve, peak, self.k)
            else:
                value = max(0, peak - self.k), min(len(self.curve) - 1, peak + self.k)
            self.intervals[peak] = value
        return self.intervals[peak]

    def clusters(self, config):
        if config.kind == "single":
            return [(peak, 1, height, height, height)
                    for peak, height in self.candidates(config.smooth, config.distance, config.p)]
        candidates, effective = [], set()
        for scale in SCALE_SETS[config.scales]:
            smooth, distance = config.smooth * scale, config.distance * scale
            physical = self.physical_scale(smooth, distance)
            if physical in effective:
                continue
            effective.add(physical)
            candidates.append(self.candidates(smooth, distance, config.p))
        return associate(candidates, max(1, round(config.association * self.k)))

    def prepare(self, clusters):
        if self.backbone == "boostingvrme":
            clusters = sorted(clusters, key=lambda item: (self.interval(item[0])[0], item[0]))
        else:
            clusters = sorted(clusters)
        peaks = np.array([item[0] for item in clusters], dtype=int)
        intervals = np.array([self.interval(int(peak)) for peak in peaks], dtype=int).reshape(-1, 2)
        n = len(peaks)
        conflicts = np.zeros((n, n), dtype=bool)
        if n and self.backbone == "boostingvrme":
            starts, ends = intervals.T
            intersection = np.maximum(0, np.minimum(ends[:, None], ends) - np.maximum(starts[:, None], starts))
            span = np.maximum(ends[:, None], ends) - np.minimum(starts[:, None], starts)
            iou = np.divide(intersection, span, out=np.zeros_like(intersection, dtype=float), where=span > 0)
            conflicts = (iou >= 0.2) | (np.abs(peaks[:, None] - peaks) <= self.k)
        gt = np.array(self.record["gt"], dtype=int).reshape(-1, 3)
        best = np.full(n, -1, dtype=int)
        if n and len(gt):
            intersection = np.maximum(0, np.minimum(intervals[:, 1, None], gt[:, 2]) - np.maximum(intervals[:, 0, None], gt[:, 0]) + 1)
            union = (intervals[:, 1] - intervals[:, 0] + 1)[:, None] + (gt[:, 2] - gt[:, 0] + 1) - intersection
            iou = intersection / union
            best = np.argmax(iou, axis=1)
            best[np.max(iou, axis=1) < 0.5] = -1
        return Prepared(clusters, intervals, conflicts, best, len(gt))


class Prepared:
    def __init__(self, clusters, intervals, conflicts, best, num_gt):
        self.clusters = clusters
        self.intervals = intervals
        self.conflicts = conflicts
        self.best = best
        self.num_gt = num_gt
        values = np.asarray(clusters, dtype=float).reshape(-1, 5)
        self.z_support = robust_z(values[:, 1])
        self.z_height = {agg: robust_z(values[:, i]) for agg, i in (("max", 2), ("mean", 3), ("top2_mean", 4))}

    def masks(self, configs):
        masks = []
        for config in configs:
            if config.kind in ("single", "union"):
                masks.append(np.ones(len(self.clusters), dtype=bool))
            else:
                score = config.weight * self.z_height[config.aggregation] + (1 - config.weight) * self.z_support
                masks.append(score >= config.tau)
        return np.asarray(masks, dtype=bool)

    def evaluate(self, configs, details=False):
        keep = self.masks(configs)
        for i in range(len(self.clusters)):
            if self.conflicts[i, i + 1:].any():
                keep[:, i + 1:] &= ~(keep[:, i, None] & self.conflicts[i, i + 1:])
        matched = np.zeros((len(configs), self.num_gt), dtype=bool)
        pred_matches = np.full(keep.shape, -1, dtype=int) if details else None
        for i, gt in enumerate(self.best):
            if gt >= 0:
                valid = keep[:, i] & ~matched[:, gt]
                matched[:, gt] |= valid
                if details:
                    pred_matches[valid, i] = gt
        tp = matched.sum(axis=1)
        counts = np.column_stack((tp, keep.sum(axis=1) - tp, self.num_gt - tp)).astype(np.int32)
        if details:
            predictions = []
            for row in range(len(configs)):
                predictions.append([{"onset": int(self.intervals[i, 0]), "offset": int(self.intervals[i, 1]),
                                     "peak": int(cluster[0]), "matched_gt": int(pred_matches[row, i])}
                                    for i, cluster in enumerate(self.clusters) if keep[row, i]])
            return counts, predictions
        return counts


def metrics(values):
    tp, fp, fn = (int(value) for value in values)
    return {"TP": tp, "FP": fp, "FN": fn,
            "precision": tp / (tp + fp) if tp + fp else 0.0,
            "recall": tp / (tp + fn) if tp + fn else 0.0,
            "F1": 2 * tp / (2 * tp + fp + fn) if 2 * tp + fp + fn else 0.0}


def choose(counts, indexes, configs):
    indexes = np.asarray(indexes, dtype=int)
    values = counts[indexes].astype(float)
    tp, fp, fn = values.T
    denom = 2 * tp + fp + fn
    f1 = np.divide(2 * tp, denom, out=np.zeros_like(tp), where=denom > 0)
    precision = np.divide(tp, tp + fp, out=np.zeros_like(tp), where=tp + fp > 0)
    # Ties favour the simpler Height-only member before deterministic grid order.
    support_cost = np.array([1 - configs[i].weight for i in indexes])
    order = np.lexsort((indexes, support_cost, fp, -precision, -f1))
    return int(indexes[order[0]])


def required_subjects(k, outer_k, inner_k):
    return (outer_k == k) | np.any(inner_k == k, axis=0)


def evaluate_k(records, subjects, backbone, k, needed, configs, single_count, batches, progress):
    subject_index = {subject: i for i, subject in enumerate(subjects)}
    videos = [(subject_index[record["subject"]], VideoFeatures(record, k, backbone))
              for record in records if needed[subject_index[record["subject"]]]]
    stats = np.zeros((len(configs), len(subjects), 3), dtype=np.int32)
    start = time.monotonic()
    for sid, video in videos:
        for index in range(single_count):
            config = configs[index]
            stats[index, sid] += video.prepare(video.clusters(config)).evaluate([config])[0]
    log(f"{progress} k={k}: single-scale complete; videos={len(videos)}")
    for group, indexes in enumerate(batches, 1):
        selected = [configs[i] for i in indexes]
        for sid, video in videos:
            prepared = video.prepare(video.clusters(selected[0]))
            stats[indexes, sid] += prepared.evaluate(selected)
        if group % 48 == 0 or group == len(batches):
            log(f"{progress} k={k}: groups={group}/{len(batches)}, elapsed={time.monotonic()-start:.0f}s")
    return stats


def baseline_audit(records, subjects, backbone, legacy_k, outer_k):
    fixed_config = Config("single", 2.0, 0.55, 1.0)
    legacy = np.zeros(3, dtype=np.int64)
    train = np.zeros((len(subjects), 3), dtype=np.int32)
    subject_index = {s: i for i, s in enumerate(subjects)}
    for record in records:
        sid = subject_index[record["subject"]]
        for k, is_legacy in ((legacy_k, True), (int(outer_k[sid]), False)):
            video = VideoFeatures(record, k, backbone)
            values = video.prepare(video.clusters(fixed_config)).evaluate([fixed_config])[0]
            if is_legacy:
                legacy += values
            else:
                train[sid] += values
    return legacy, train


def paired_bootstrap(first, second, repeats=10000, seed=20260906):
    rng = np.random.default_rng(seed)
    n = len(first)
    draws = rng.integers(0, n, size=(repeats, n))
    def f1(array):
        values = array[draws].sum(axis=1).astype(float)
        denom = 2 * values[:, 0] + values[:, 1] + values[:, 2]
        return np.divide(2 * values[:, 0], denom, out=np.zeros(repeats), where=denom > 0)
    deltas = f1(first) - f1(second)
    low, high = np.quantile(deltas, [0.025, 0.975])
    return {"delta_F1": metrics(first.sum(axis=0))["F1"] - metrics(second.sum(axis=0))["F1"],
            "ci95": [float(low), float(high)], "positive_resample_fraction": float(np.mean(deltas > 0)),
            "repeats": repeats, "seed": seed,
            "scope": "paired subjects, conditional on frozen OOF predictions and selected fold configurations"}


def event_changes(first, second):
    rescued = lost = preserved = added_fp = removed_fp = 0
    for current, reference in zip(first, second):
        a = {p["matched_gt"] for p in current if p["matched_gt"] >= 0}
        b = {p["matched_gt"] for p in reference if p["matched_gt"] >= 0}
        rescued += len(a - b)
        lost += len(b - a)
        preserved += len(a & b)
        fp_a = {(p["onset"], p["peak"], p["offset"]) for p in current if p["matched_gt"] < 0}
        fp_b = {(p["onset"], p["peak"], p["offset"]) for p in reference if p["matched_gt"] < 0}
        added_fp += len(fp_a - fp_b)
        removed_fp += len(fp_b - fp_a)
    return {"GT_rescued": rescued, "GT_lost": lost, "GT_preserved": preserved,
            "net_TP": rescued - lost, "FP_added_exact_interval": added_fp,
            "FP_removed_exact_interval": removed_fp, "net_FP": added_fp - removed_fp}


def select_and_replay(records, subjects, backbone, outer_k, inner_k, stats, configs, native_train, target):
    pools = {
        "single_tuned": [i for i, c in enumerate(configs) if c.kind == "single"],
        "multiscale_union": [i for i, c in enumerate(configs) if c.kind == "union"],
        "multiscale_height": [i for i, c in enumerate(configs) if c.kind == "score" and c.weight == 1],
        "multiscale_height_support": [i for i, c in enumerate(configs) if c.kind == "score"],
        "multiscale_fusion_only": [i for i, c in enumerate(configs) if c.kind == "score" and c.weight < 1],
    }
    lookup = {c: i for i, c in enumerate(configs)}
    native_index = lookup[Config("single", 2.0, 0.55, 1.0)]
    choices = {name: [] for name in LABELS}
    rows = []
    counts_by_family = {name: np.zeros((len(subjects), 3), dtype=np.int32) for name in LABELS}
    for held, subject in enumerate(subjects):
        inner = np.zeros((len(configs), 3), dtype=np.int64)
        for validation in range(len(subjects)):
            if held != validation:
                inner += stats[int(inner_k[held, validation])][:, validation]
        selected = {name: choose(inner, indexes, configs) for name, indexes in pools.items()}
        selected["native_train_k"] = native_index
        height_config = configs[selected["multiscale_height"]]
        matched = [lookup[Config(**{**asdict(height_config), "weight": weight})] for weight in WEIGHTS]
        selected["support_matched_height"] = choose(inner, matched, configs)
        for name in LABELS:
            index = selected[name]
            choices[name].append(index)
            test = stats[int(outer_k[held])][index, held]
            counts_by_family[name][held] = test
            rows.append({"family": name, "subject": subject, "k_train_only": int(outer_k[held]),
                         "config_id": index, "config": configs[index].identifier,
                         "inner_F1": metrics(inner[index])["F1"], **metrics(test)})
    if not np.array_equal(counts_by_family["native_train_k"], native_train):
        raise AssertionError("Fold-native replay differs from audit")
    csv_write(target / "outer_loso_selections.csv", rows)
    all_predictions = {name: [] for name in LABELS}
    sid_lookup = {subject: i for i, subject in enumerate(subjects)}
    replay_counts = {name: np.zeros_like(native_train) for name in LABELS}
    per_video = []
    for vid, record in enumerate(records):
        sid = sid_lookup[record["subject"]]
        video = VideoFeatures(record, int(outer_k[sid]), backbone)
        prepared_cache = {}
        for name in LABELS:
            config = configs[choices[name][sid]]
            key = (config.kind == "single", config.generation)
            if key not in prepared_cache:
                prepared_cache[key] = video.prepare(video.clusters(config))
            values, predictions = prepared_cache[key].evaluate([config], details=True)
            all_predictions[name].append(predictions[0])
            replay_counts[name][sid] += values[0]
        per_video.append({"video_index": vid, "subject": record["subject"], "video": record["video"],
                          "gt": record["gt"], "predictions": {name: all_predictions[name][-1] for name in LABELS}})
    for name in LABELS:
        if not np.array_equal(replay_counts[name], counts_by_family[name]):
            raise AssertionError(f"Selected-config replay failed: {name}")
    json_write(target / "selected_predictions.json", per_video)
    csv_write(target / "subject_counts.csv", [{"family": name, "subject": subject,
                                               **metrics(counts_by_family[name][i])}
                                              for name in LABELS for i, subject in enumerate(subjects)])
    comparisons = {}
    pairs = [(name, "native_train_k") for name in LABELS if name != "native_train_k"]
    pairs += [(name, "multiscale_height") for name in ("multiscale_height_support", "support_matched_height", "multiscale_fusion_only")]
    pairs += [("multiscale_height_support", "single_tuned")]
    for name, reference in pairs:
        changes = event_changes(all_predictions[name], all_predictions[reference])
        delta = counts_by_family[name].sum(axis=0) - counts_by_family[reference].sum(axis=0)
        if changes["net_TP"] != delta[0] or changes["net_FP"] != delta[1]:
            raise AssertionError("Event accounting mismatch")
        comparisons[f"{name}_vs_{reference}"] = {
            **paired_bootstrap(counts_by_family[name], counts_by_family[reference]), **changes}
    return {
        "metrics": {name: metrics(values.sum(axis=0)) for name, values in counts_by_family.items()},
        "comparisons": comparisons,
        "selection_frequency": {name: dict(Counter(configs[i].identifier for i in choices[name]).most_common()) for name in LABELS},
        "support_weight_frequency": {name: dict(Counter(str(configs[i].weight) for i in choices[name]).most_common())
                                     for name in ("multiscale_height_support", "support_matched_height")},
        "verification": {"selected_prediction_replay": True, "GT_FP_accounting": True,
                         "held_subject_excluded_from_k_and_objective": True},
    }



def run(backbone, dataset, audit_only=False):
    records, subjects, legacy_k, cache_path = load_data(backbone, dataset)
    outer_k, inner_k = fold_priors(records, subjects, backbone)
    legacy, native_train = baseline_audit(records, subjects, backbone, legacy_k, outer_k)
    if tuple(legacy) != EXPECTED[backbone, dataset]:
        raise AssertionError(f"Legacy Native mismatch: {legacy}, expected {EXPECTED[backbone, dataset]}")
    log(f"[{backbone}/{dataset}] legacy={metrics(legacy)}, train-k={metrics(native_train.sum(axis=0))}")
    log(f"[{backbone}/{dataset}] outer k={dict(Counter(outer_k))}; inner k={dict(Counter(inner_k[inner_k>0]))}")
    if audit_only:
        return
    target = WORKSPACE / backbone / "results" / "equiscale_fair_validation" / dataset
    target.mkdir(parents=True, exist_ok=True)
    configs, single_count, batches = configuration_grid()
    spec = protocol_spec()
    manifest = {"protocol": spec, "backbone": backbone, "dataset": dataset,
                "input_path": str(cache_path), "input_sha256": digest(cache_path),
                "engine_sha256": digest(__file__), "helper_sha256": digest(Path(__file__).with_name("tune_equiscale.py"))}
    signature = hashlib.sha256(json.dumps(manifest, sort_keys=True).encode()).hexdigest()
    manifest["signature"] = signature
    protocol_path = target / "PROTOCOL.json"
    if protocol_path.exists() and json.loads(protocol_path.read_text(encoding="utf-8"))["signature"] != signature:
        raise RuntimeError("Existing protocol differs. Preserve it and use a new result directory/version.")
    json_write(protocol_path, manifest)
    json_write(target / "configurations.json", [{"config_id": i, **asdict(c)} for i, c in enumerate(configs)])
    json_write(target / "fold_duration_priors.json", {"subjects": subjects, "outer": outer_k.tolist(), "inner": inner_k.tolist()})
    stats = {}
    ks = sorted(set(outer_k) | set(inner_k[inner_k > 0]))
    for k in ks:
        path = target / f"stats_k{k}.npz"
        needed = required_subjects(k, outer_k, inner_k)
        if path.exists():
            with np.load(path, allow_pickle=False) as cached:
                if str(cached["signature"]) != signature or not np.array_equal(cached["needed"], needed):
                    raise AssertionError("Stale count cache")
                stats[k] = cached["stats"]
            log(f"[{backbone}/{dataset}] reused k={k} counts")
            continue
        stats[k] = evaluate_k(records, subjects, backbone, int(k), needed, configs, single_count, batches, f"[{backbone}/{dataset}]")
        np.savez_compressed(path, stats=stats[k], needed=needed, signature=np.array(signature))
    result = select_and_replay(records, subjects, backbone, outer_k, inner_k, stats, configs, native_train, target)
    report = {"backbone": backbone, "dataset": dataset, "videos": len(records), "subjects": len(subjects),
              "GT_events": sum(len(r["gt"]) for r in records), "manifest_signature": signature,
              "legacy_baseline_audit": {"k": legacy_k, "metrics": metrics(legacy), "matches_expected": True},
              "outer_k_frequency": dict(Counter(str(k) for k in outer_k)),
              "inner_k_frequency": dict(Counter(str(k) for k in inner_k[inner_k > 0])), **result}
    json_write(target / "report.json", report)
    write_summary(backbone)
    log(f"[{backbone}/{dataset}] COMPLETE " + str({name: round(m['F1'], 4) for name, m in result['metrics'].items()}))


def main(default_backbone="boostingvrme"):
    parser = argparse.ArgumentParser()
    parser.add_argument("--backbone", choices=("metst", "boostingvrme"), default=default_backbone)
    parser.add_argument("--dataset", choices=("sammlv", "casme3", "both"), default="both")
    parser.add_argument("--audit-only", action="store_true")
    args = parser.parse_args()
    for dataset in (("sammlv", "casme3") if args.dataset == "both" else (args.dataset,)):
        run(args.backbone, dataset, args.audit_only)


if __name__ == "__main__":
    main()

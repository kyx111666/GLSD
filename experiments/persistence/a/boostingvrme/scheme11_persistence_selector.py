"""Scheme 11 nested-LOSO persistence policy selector for BoostingVRME curves.

This is a post-processing experiment.  It consumes only the curve caches
generated by run_persistence_selector.py and writes results beside this file.
"""

from __future__ import annotations

import argparse
import csv
import json
import pickle
from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Sequence, Tuple

import numpy as np


ROOT = Path(__file__).resolve().parent
CURVE_CACHE = ROOT / "curve_cache"
RESULT_ROOT = ROOT / "results" / "scheme11_persistence_selector"

STRICT_SMOOTH_MULTIPLIER = 2.0
STRICT_CANDIDATE_FACTOR = 0.65
STRICT_DISTANCE_MULTIPLIER = 1.5
STRICT_PERSISTENCE_THRESHOLD = 1.0
RECOVERY_SCALES = (1.0, 1.5, 2.0)
RECOVERY_HIGH_FACTOR = 0.65


@dataclass(frozen=True)
class Counts:
    tp: int = 0
    fp: int = 0
    fn: int = 0

    def add(self, other: "Counts") -> "Counts":
        return Counts(self.tp + other.tp, self.fp + other.fp, self.fn + other.fn)

    def subtract(self, other: "Counts") -> "Counts":
        return Counts(self.tp - other.tp, self.fp - other.fp, self.fn - other.fn)

    def f1(self) -> float:
        denominator = 2 * self.tp + self.fp + self.fn
        return 2 * self.tp / denominator if denominator else 0.0

    def precision(self) -> float:
        denominator = self.tp + self.fp
        return self.tp / denominator if denominator else 0.0

    def recall(self) -> float:
        denominator = self.tp + self.fn
        return self.tp / denominator if denominator else 0.0

    def as_dict(self) -> dict:
        return {
            "TP": self.tp,
            "FP": self.fp,
            "FN": self.fn,
            "precision": self.precision(),
            "recall": self.recall(),
            "F1": self.f1(),
        }


@dataclass(frozen=True)
class CascadeConfig:
    p_low: float
    local_window_multiplier: float
    alignment_multiplier: float
    local_persistence_threshold: float
    global_persistence_threshold: float
    recovery_mode: str

    @property
    def identifier(self) -> str:
        return (
            f"dual_path|p_low={self.p_low:g}|r={self.local_window_multiplier:g}"
            f"|a={self.alignment_multiplier:g}|tau_local={self.local_persistence_threshold:g}"
            f"|tau_global={self.global_persistence_threshold:g}|mode={self.recovery_mode}"
        )


@dataclass(frozen=True)
class LocalOnlyConfig:
    p: float
    local_window_multiplier: float
    alignment_multiplier: float
    persistence_threshold: float

    @property
    def identifier(self) -> str:
        return (
            f"local_multiscale_only|p={self.p:g}|r={self.local_window_multiplier:g}"
            f"|a={self.alignment_multiplier:g}|tau={self.persistence_threshold:g}"
        )


@dataclass
class GlobalFeatures:
    curve: np.ndarray
    peaks: np.ndarray
    persistence_z: np.ndarray


@dataclass
class ScaleFeatures:
    curve: np.ndarray
    peaks: np.ndarray
    persistence_z: np.ndarray


@dataclass
class LocalFeatures:
    scale_features: Dict[float, ScaleFeatures]


Detection = Tuple[int, int, int]


def moving_average(values: np.ndarray, width: int) -> np.ndarray:
    width = max(1, int(width))
    return np.convolve(np.asarray(values, dtype=float), np.ones(width) / width, mode="same")


def local_maxima(values: np.ndarray, minimum_height: float, distance: int) -> np.ndarray:
    values = np.asarray(values, dtype=float)
    if values.size < 3:
        return np.empty(0, dtype=int)
    peaks: List[int] = []
    index = 1
    while index < values.size - 1:
        if values[index] > values[index - 1]:
            left = index
            while index + 1 < values.size and values[index] == values[index + 1]:
                index += 1
            if index < values.size - 1 and values[index] > values[index + 1]:
                peak = (left + index) // 2
                if values[peak] >= minimum_height:
                    peaks.append(peak)
        index += 1
    if not peaks:
        return np.empty(0, dtype=int)
    priority = sorted(peaks, key=lambda point: (-values[point], point))
    kept: List[int] = []
    for point in priority:
        if all(abs(point - chosen) >= max(1, int(distance)) for chosen in kept):
            kept.append(point)
    return np.asarray(sorted(kept), dtype=int)


def robust_z(values: np.ndarray) -> np.ndarray:
    values = np.asarray(values, dtype=float)
    if not len(values):
        return values
    median = float(np.median(values))
    scale = 1.4826 * float(np.median(np.abs(values - median)))
    if scale <= 1e-12:
        scale = float(np.std(values))
    return (values - median) / scale if scale > 1e-12 else np.zeros_like(values)


def peak_prominence(values: np.ndarray, peak: int) -> float:
    height = float(values[peak])
    left_min = right_min = height
    index = peak
    while index > 0:
        index -= 1
        current = float(values[index])
        if current > height:
            break
        left_min = min(left_min, current)
    index = peak
    while index < len(values) - 1:
        index += 1
        current = float(values[index])
        if current > height:
            break
        right_min = min(right_min, current)
    return max(0.0, height - max(left_min, right_min))


def local_prominence(values: np.ndarray, peak: int, radius: int) -> float:
    left = values[max(0, peak - radius) : peak + 1]
    right = values[peak : min(len(values), peak + radius + 1)]
    return max(0.0, float(values[peak]) - max(float(np.min(left)), float(np.min(right))))


def interval_iou(first: Detection, second: Sequence[int]) -> float:
    left = max(first[0], int(second[0]))
    right = min(first[1], int(second[2]))
    intersection = max(0, right - left + 1)
    if not intersection:
        return 0.0
    union = (first[1] - first[0] + 1) + (int(second[2]) - int(second[0]) + 1) - intersection
    return intersection / union


def fixed_detection(point: int, curve_length: int, k_p: int) -> Detection:
    return max(0, point - k_p), min(curve_length - 1, point + k_p), int(point)


def count_video(detections: Sequence[Detection], record: dict) -> Counts:
    matched: set[int] = set()
    tp = fp = 0
    for detection in detections:
        overlaps = [interval_iou(detection, sample) for sample in record["gt"]]
        best = int(np.argmax(overlaps)) if overlaps else -1
        if best >= 0 and overlaps[best] >= 0.5 and best not in matched:
            matched.add(best)
            tp += 1
        else:
            fp += 1
    return Counts(tp=tp, fp=fp, fn=len(record["gt"]) - len(matched))


def aggregate(items: Iterable[Counts]) -> Counts:
    total = Counts()
    for item in items:
        total = total.add(item)
    return total


def groups(records: Sequence[dict]) -> Dict[str, List[int]]:
    output: Dict[str, List[int]] = defaultdict(list)
    for index, record in enumerate(records):
        output[str(record["subject"])].append(index)
    return dict(output)


def k_prime(records: Sequence[dict]) -> int:
    durations = sorted(sample[2] - sample[0] for record in records for sample in record["gt"])
    return int((durations[len(durations) // 2] + 1) / 2)


def native_fixed(curve: np.ndarray, k_p: int) -> List[Detection]:
    smoothed = moving_average(curve, 2 * k_p)
    threshold = float(smoothed.mean() + 0.55 * (smoothed.max() - smoothed.mean()))
    return [fixed_detection(int(peak), len(curve), k_p) for peak in local_maxima(smoothed, threshold, k_p)]


def global_features(curve: np.ndarray, k_p: int, distance_multiplier: float) -> GlobalFeatures:
    smoothed = moving_average(curve, round(STRICT_SMOOTH_MULTIPLIER * k_p))
    peaks = local_maxima(smoothed, -np.inf, round(distance_multiplier * k_p))
    persistence = np.asarray([peak_prominence(smoothed, int(peak)) for peak in peaks], dtype=float)
    return GlobalFeatures(smoothed, peaks, robust_z(persistence))


def strict_detections(features: GlobalFeatures, curve_length: int, k_p: int) -> List[Detection]:
    threshold = float(features.curve.mean() + STRICT_CANDIDATE_FACTOR * (features.curve.max() - features.curve.mean()))
    return [
        fixed_detection(int(peak), curve_length, k_p)
        for peak, score in zip(features.peaks, features.persistence_z)
        if features.curve[peak] >= threshold and score >= STRICT_PERSISTENCE_THRESHOLD
    ]


def build_local_features(curve: np.ndarray, k_p: int, window_multiplier: float) -> LocalFeatures:
    radius = max(1, round(window_multiplier * k_p))
    output: Dict[float, ScaleFeatures] = {}
    for scale in RECOVERY_SCALES:
        smoothed = moving_average(curve, round(scale * k_p))
        peaks = local_maxima(smoothed, -np.inf, k_p)
        persistence = np.asarray([local_prominence(smoothed, int(peak), radius) for peak in peaks], dtype=float)
        output[scale] = ScaleFeatures(smoothed, peaks, robust_z(persistence))
    return LocalFeatures(output)


def nearest_persistence(features: ScaleFeatures, point: int, tolerance: int) -> float | None:
    indexes = np.flatnonzero(np.abs(features.peaks - point) <= tolerance)
    if not len(indexes):
        return None
    best = min(indexes.tolist(), key=lambda index: (abs(int(features.peaks[index]) - point), -features.persistence_z[index]))
    return float(features.persistence_z[best])


def local_candidates(features: LocalFeatures, k_p: int, config: CascadeConfig | LocalOnlyConfig) -> List[Tuple[int, float]]:
    reference = features.scale_features[1.5]
    threshold = float(reference.curve.mean() + config.p_low * (reference.curve.max() - reference.curve.mean())) if isinstance(config, CascadeConfig) else float(reference.curve.mean() + config.p * (reference.curve.max() - reference.curve.mean()))
    tolerance = max(1, round(config.alignment_multiplier * k_p))
    candidates: List[Tuple[int, float]] = []
    for peak in reference.peaks:
        if reference.curve[peak] < threshold:
            continue
        scores = [nearest_persistence(features.scale_features[scale], int(peak), tolerance) for scale in RECOVERY_SCALES]
        if any(score is None for score in scores):
            continue
        candidates.append((int(peak), float(min(scores))))
    return candidates


def closest_global(features: GlobalFeatures, point: int, tolerance: int) -> Tuple[int, float] | None:
    indexes = np.flatnonzero(np.abs(features.peaks - point) <= tolerance)
    if not len(indexes):
        return None
    best = min(indexes.tolist(), key=lambda index: (abs(int(features.peaks[index]) - point), -features.persistence_z[index]))
    return int(features.peaks[best]), float(features.persistence_z[best])


def cascade_detections(
    strict: Sequence[Detection], recovery_global: GlobalFeatures, local: LocalFeatures,
    curve_length: int, k_p: int, config: CascadeConfig,
) -> List[Detection]:
    reference = local.scale_features[1.5].curve
    recovery_upper = float(reference.mean() + RECOVERY_HIGH_FACTOR * (reference.max() - reference.mean()))
    output = list(strict)
    strict_points = [item[2] for item in strict]
    for point, local_score in local_candidates(local, k_p, config):
        if local_score < config.local_persistence_threshold:
            continue
        if config.recovery_mode == "low_band" and reference[point] >= recovery_upper:
            continue
        global_match = closest_global(recovery_global, point, k_p)
        if global_match is None:
            continue
        global_point, global_score = global_match
        if global_score < config.global_persistence_threshold:
            continue
        if any(abs(global_point - strict_point) <= k_p for strict_point in strict_points):
            continue
        output.append(fixed_detection(global_point, curve_length, k_p))
    return sorted(output, key=lambda item: item[2])


def local_only_detections(local: LocalFeatures, curve_length: int, k_p: int, config: LocalOnlyConfig) -> List[Detection]:
    return [
        fixed_detection(point, curve_length, k_p)
        for point, score in local_candidates(local, k_p, config)
        if score >= config.persistence_threshold
    ]


def cascade_configs() -> List[CascadeConfig]:
    return [
        CascadeConfig(p, r, a, tau_local, tau_global, mode)
        for p in (0.25, 0.35, 0.45)
        for r in (0.5, 1.0, 1.5)
        for a in (0.25, 0.5, 1.0)
        for tau_local in (0.5, 1.0)
        for tau_global in (-0.5, 0.0, 0.5, 1.0)
        for mode in ("low_band", "strict_missed")
    ]


def local_configs() -> List[LocalOnlyConfig]:
    return [
        LocalOnlyConfig(p, r, a, tau)
        for p in (0.25, 0.35, 0.45)
        for r in (0.5, 1.0, 1.5)
        for a in (0.25, 0.5, 1.0)
        for tau in (0.5, 1.0)
    ]


def evaluate_by_subject(records: Sequence[dict], grouped: Dict[str, List[int]], detections: Sequence[Sequence[Detection]]) -> Dict[str, Counts]:
    return {
        subject: aggregate(count_video(detections[index], records[index]) for index in indexes)
        for subject, indexes in grouped.items()
    }


def score_key(counts: Counts, identifier: str) -> Tuple[float, float, int, str]:
    return counts.f1(), counts.precision(), -counts.fp, identifier


def select_outer_loso(
    grouped: Dict[str, List[int]],
    native_stats: Dict[str, Counts],
    strict_stats: Dict[str, Counts],
    cascade_stats: Dict[str, Dict[str, Counts]],
    local_stats: Dict[str, Dict[str, Counts]],
) -> Tuple[Counts, List[dict]]:
    native_total = aggregate(native_stats.values())
    strict_total = aggregate(strict_stats.values())
    cascade_totals = {identifier: aggregate(stats.values()) for identifier, stats in cascade_stats.items()}
    local_totals = {identifier: aggregate(stats.values()) for identifier, stats in local_stats.items()}
    final = Counts()
    rows = []
    for subject in grouped:
        options = [
            (score_key(native_total.subtract(native_stats[subject]), "zz_native_fixed"), "native_fixed", native_stats[subject]),
            (score_key(strict_total.subtract(strict_stats[subject]), "strict_global"), "strict_global", strict_stats[subject]),
        ]
        options.extend(
            (score_key(total.subtract(cascade_stats[identifier][subject]), identifier), identifier, cascade_stats[identifier][subject])
            for identifier, total in cascade_totals.items()
        )
        options.extend(
            (score_key(total.subtract(local_stats[identifier][subject]), identifier), identifier, local_stats[identifier][subject])
            for identifier, total in local_totals.items()
        )
        score, selected, test_counts = max(options, key=lambda item: item[0])
        final = final.add(test_counts)
        rows.append({
            "subject": subject,
            "selected_config": selected,
            "inner_raw_f1": round(score[0], 6),
            "test_raw_f1": round(test_counts.f1(), 6),
        })
    return final, rows


def select_cascade_only(
    grouped: Dict[str, List[int]], cascade_stats: Dict[str, Dict[str, Counts]]
) -> Tuple[Counts, List[dict]]:
    totals = {identifier: aggregate(stats.values()) for identifier, stats in cascade_stats.items()}
    final = Counts()
    rows = []
    for subject in grouped:
        options = [
            (score_key(total.subtract(cascade_stats[identifier][subject]), identifier), identifier, cascade_stats[identifier][subject])
            for identifier, total in totals.items()
        ]
        score, selected, test_counts = max(options, key=lambda item: item[0])
        final = final.add(test_counts)
        rows.append({
            "subject": subject,
            "selected_config": selected,
            "inner_raw_f1": round(score[0], 6),
            "test_raw_f1": round(test_counts.f1(), 6),
        })
    return final, rows


def scheme11_native_stats(records: Sequence[dict], grouped: Dict[str, List[int]], curves: Sequence[np.ndarray], k_p: int) -> Tuple[Dict[str, Counts], List[List[Detection]]]:
    detections = [native_fixed(curve, k_p) for curve in curves]
    return evaluate_by_subject(records, grouped, detections), detections


def run_dataset(name: str) -> dict:
    cache_stem = {"sammlv": "sammlv", "casme3": "casme_3"}[name]
    package_path = CURVE_CACHE / f"{cache_stem}_curves.pkl"
    with package_path.open("rb") as handle:
        package = pickle.load(handle)
    records = package["records"]
    curves = [np.asarray(curve, dtype=float) for curve in package["curves"]]
    if len(records) != len(curves) or not all(np.isfinite(curve).all() for curve in curves):
        raise RuntimeError(f"{name}: invalid curve cache")
    k_p = k_prime(records)
    grouped = groups(records)
    print(f"[{package['dataset']}] Scheme 11: {len(records)} videos, {len(grouped)} subjects, k_p={k_p}", flush=True)

    native_stats, _native_detections = scheme11_native_stats(records, grouped, curves, k_p)
    strict_features = [global_features(curve, k_p, STRICT_DISTANCE_MULTIPLIER) for curve in curves]
    recovery_global = [global_features(curve, k_p, 1.0) for curve in curves]
    strict_detections_by_video = [strict_detections(features, len(curve), k_p) for features, curve in zip(strict_features, curves)]
    strict_stats = evaluate_by_subject(records, grouped, strict_detections_by_video)

    cascade_stats: Dict[str, Dict[str, Counts]] = {}
    local_stats: Dict[str, Dict[str, Counts]] = {}
    cascade_config_list = cascade_configs()
    local_config_list = local_configs()
    for position, window_multiplier in enumerate((0.5, 1.0, 1.5), start=1):
        print(f"[{package['dataset']}] local feature group {position}/3: r={window_multiplier:g}", flush=True)
        local_feature_cache = [build_local_features(curve, k_p, window_multiplier) for curve in curves]
        for config in cascade_config_list:
            if config.local_window_multiplier != window_multiplier:
                continue
            detections = [
                cascade_detections(strict, global_feature, local, len(curve), k_p, config)
                for strict, global_feature, local, curve in zip(strict_detections_by_video, recovery_global, local_feature_cache, curves)
            ]
            cascade_stats[config.identifier] = evaluate_by_subject(records, grouped, detections)
        for config in local_config_list:
            if config.local_window_multiplier != window_multiplier:
                continue
            detections = [local_only_detections(local, len(curve), k_p, config) for local, curve in zip(local_feature_cache, curves)]
            local_stats[config.identifier] = evaluate_by_subject(records, grouped, detections)

    cascade_only, cascade_rows = select_cascade_only(grouped, cascade_stats)
    selector, selector_rows = select_outer_loso(grouped, native_stats, strict_stats, cascade_stats, local_stats)
    summary = {
        "dataset": package["dataset"],
        "curve_cache": str(package_path),
        "videos": len(records),
        "subjects": len(grouped),
        "gt_events": sum(len(record["gt"]) for record in records),
        "k_p": k_p,
        "protocol": {
            "selection": "outer LOSO; policy/configuration selected by aggregate inner raw Spotting F1",
            "matching": "chronological top-IoU greedy, IoU=0.5",
            "policy_pool": "native fixed + strict global + 432 dual-path cascades + 54 local-only configurations",
            "intervals": "scheme11 fixed peak plus or minus k_p for every scheme11 policy",
            "raw_only": True,
        },
        "scheme11_native_fixed": aggregate(native_stats.values()).as_dict(),
        "strict_global_path": aggregate(strict_stats.values()).as_dict(),
        "dual_path_only_nested_loso": cascade_only.as_dict(),
        "dual_path_selected_config_frequency": dict(Counter(row["selected_config"] for row in cascade_rows).most_common()),
        "policy_selector_nested_loso": selector.as_dict(),
        "selected_config_frequency": dict(Counter(row["selected_config"] for row in selector_rows).most_common()),
    }
    target = RESULT_ROOT / name
    target.mkdir(parents=True, exist_ok=True)
    (target / "report.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    with (target / "outer_loso_dual_path_only.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=["subject", "selected_config", "inner_raw_f1", "test_raw_f1"])
        writer.writeheader()
        writer.writerows(cascade_rows)
    with (target / "outer_loso_policy_selection.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=["subject", "selected_config", "inner_raw_f1", "test_raw_f1"])
        writer.writeheader()
        writer.writerows(selector_rows)
    return summary


def write_summary(reports: Sequence[dict]) -> None:
    lines = ["# BoostingVRME 方案 11 Persistence 策略选择器测试", "", "## 协议", "", "- 复用本目录已验证的 BoostingVRME 原始检测曲线缓存，不重新训练或修改原项目。", "- 按方案 11 的固定区间版本：所有竞争策略使用 `peak +/- k_p`；因此不与 BoostingVRME 原生的可变区间 Native 直接混合。", "- 每个外层留出被试仅使用其余被试的汇总 Raw Spotting F1，在 Native fixed、严格全局、432 个双路径级联和 54 个纯局部配置中选择。", "", "## 结果", "", "| 数据集 | 方案11 Native fixed F1 | 严格全局 F1 | 双路径级联 F1 | 策略选择器 F1 | 选择器 TP/FP/FN |", "| - | -: | -: | -: | -: | - |"]
    for report in reports:
        native = report["scheme11_native_fixed"]
        strict = report["strict_global_path"]
        cascade = report["dual_path_only_nested_loso"]
        selector = report["policy_selector_nested_loso"]
        lines.append(f"| {report['dataset']} | {native['F1']:.4f} | {strict['F1']:.4f} | {cascade['F1']:.4f} | {selector['F1']:.4f} | {selector['TP']}/{selector['FP']}/{selector['FN']} |")
    lines.extend(["", "## 选择频次", ""])
    for report in reports:
        frequencies = report["selected_config_frequency"]
        lines.append(f"- `{report['dataset']}`：`{frequencies}`")
        lines.append(f"  双路径级联单独竞争时：`{report['dual_path_selected_config_frequency']}`")
    lines.extend(["", "## 解释", "", "方案 11 是策略级路由器。它允许 SAMMLV 选择严格全局过滤，也允许 CASME3 选择低门槛局部或双路径级联，但不会直接把两个通道的全部检测结果强行并集。", "", "本轮为探索性迁移测试：候选池和网格继承自 ME-TST 方案 11。所有选择均为嵌套 LOSO，但仍应在未参与方法设计的独立数据上复验。"])
    (RESULT_ROOT / "SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Run Scheme 11 on BoostingVRME curve caches")
    parser.add_argument("--datasets", choices=["sammlv", "casme3", "both"], default="both")
    args = parser.parse_args()
    requested = ["sammlv", "casme3"] if args.datasets == "both" else [args.datasets]
    RESULT_ROOT.mkdir(parents=True, exist_ok=True)
    reports = [run_dataset(name) for name in requested]
    write_summary(reports)


if __name__ == "__main__":
    main()
